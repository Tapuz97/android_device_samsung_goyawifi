"""Expose only ANI7-imported private Bionic helpers, with their exact ARM ABI.

The runtime already exports these compatibility functions. Vendor SDK stubs do
not. PIC ARM tail trampolines forward to the actual libc implementation and keep
multi-register EABI results intact; no math or FILE layout is reimplemented.
"""
from pathlib import Path
import json
import re
import subprocess

audit = Path('/root/t110-android13-audit')
product = Path('/root/t110-android13/android/device/samsung/t110_bringup/audio')
libc = Path('/root/t110-android13/out/target/product/t110_bringup/system/lib/bootstrap/libc.so')
symbols = subprocess.check_output(['readelf', '--dyn-syms', '-W', str(libc)], text=True, stderr=subprocess.DEVNULL)
private = set(re.findall(r'\b(\w+)@@LIBC_PRIVATE\b', symbols))
usage = {}
for item in json.loads((audit / 'vendor-audio-packaging.json').read_text()):
    blob = product / item['path']
    table = subprocess.check_output(['readelf', '--dyn-syms', '-W', str(blob)], text=True)
    imports = set()
    for line in table.splitlines():
        columns = line.split()
        if len(columns) >= 8 and columns[4] == 'GLOBAL' and columns[6] == 'UND':
            imports.add(columns[7].split('@')[0])
    needed = sorted(imports & private)
    assert all(n.startswith('__aeabi_') or n in {'__srget', '__swbuf', '__popcountsi2'} for n in needed), needed
    if needed:
        usage[item['name']] = needed
names = sorted(set().union(*(set(v) for v in usage.values())))
assert names and len(names) < 80, names

resolver = '''/* SPDX-License-Identifier: Apache-2.0 */
#include <dlfcn.h>
#include <cstdlib>

// Exact private ABI used by this device's stock audio binaries. An explicit
// libc handle avoids RTLD_NEXT ordering and accidental recursion into our shim.
extern "C" __attribute__((visibility("hidden")))
void* t110_resolve_legacy_libc(const char* name, void** slot) {
    static void* const libc = dlopen("libc.so", RTLD_NOW | RTLD_LOCAL);
    if (!libc) std::abort();
    void* const target = dlsym(libc, name);
    if (!target) std::abort();
    __atomic_store_n(slot, target, __ATOMIC_RELEASE);
    return target;
}
'''
assembly = '''/* SPDX-License-Identifier: Apache-2.0 */
// Generated by prepare_legacy_libc_bridge.py; ARM32 only, exact imported helpers.
// All whitelisted functions use base AAPCS (core-register args/results).
// Preserve r0-r3, caller SP and LR through first resolution. Tail branching
// preserves idivmod/ldivmod's multi-register results and stack arguments.
// The slot address is PC-relative: this shim must not need text relocations.
.syntax unified
.arm
.text
.hidden t110_resolve_legacy_libc
'''
for name in names:
    assembly += f'''
.align 2
.global {name}
.type {name}, %function
{name}:
    ldr ip, .Loffset_{name}
.Lbase_{name}:
    add ip, pc, ip
    ldr ip, [ip]
    dmb ish
    cmp ip, #0
    bxne ip
    push {{r0-r3, ip, lr}}
    adr r0, .Lname_{name}
    ldr r1, .Loffset2_{name}
.Lbase2_{name}:
    add r1, pc, r1
    bl t110_resolve_legacy_libc
    str r0, [sp, #16]
    pop {{r0-r3, ip, lr}}
    bx ip
.Loffset_{name}:
    .word .Lslot_{name} - (.Lbase_{name} + 8)
.Loffset2_{name}:
    .word .Lslot_{name} - (.Lbase2_{name} + 8)
.Lname_{name}:
    .asciz "{name}"
.size {name}, . - {name}
.pushsection .bss
.align 2
.Lslot_{name}:
    .word 0
.popsection
'''
assembly += '\n.section .note.GNU-stack,"",%progbits\n'
(product / 'LegacyLibc.cpp').write_text(resolver)
(product / 'LegacyLibcTrampolines.S').write_text(assembly)
# Distinct basename: Soong maps both .cpp and .S to basename.o in this module.
obsolete = product / 'LegacyLibc.S'
if obsolete.exists():
    assert obsolete.read_text().startswith('/* SPDX-License-Identifier: Apache-2.0 */\n// Generated by prepare_legacy_libc_bridge.py;')
    obsolete.unlink()
(audit / 'legacy-libc-bridge.json').write_text(json.dumps(dict(symbols=names, usage=usage,
    provider='Android13 Bionic libc LIBC_PRIVATE compatibility exports',
    strategy='PIC ARM tail trampoline; exact base AAPCS; no reimplementation'), indent=2) + '\n')
print(f'Generated exact ARM trampolines for {len(names)} existing Bionic helpers used by {len(usage)} ANI7 libraries.')
